test('reload restores authenticated booking details and requires a fresh quote and terms', async () => {
  api.post.mockReset();
  const user = { _id: 'buyer', isPhoneVerified: true, name: 'Buyer', phone: '9876543210', email: 'account@example.test' };
  const props = { listings: [listing], configuration, user, storeSlug: 'bridal', initialItems: [{ listingId: 'list1', quantity: 1 }], initialSchedule: { pickupAt: '2030-01-10T10:00', returnDueAt: '2030-01-12T10:00' } };
  api.post.mockResolvedValue({ timezone: 'Asia/Kolkata', policyRevision: 1, quoteFingerprint: 'fresh', terms: 'Fresh terms', schedule: {}, quote: { rentalPaise: 100000, depositPaise: 0, advanceRentPaise: 30000, dueNowPaise: 30000 } });
  const first = render(<RentalBookingForm {...props} />);
  fireEvent.click(screen.getByRole('button', { name: 'Check dates & review price' }));
  await screen.findByRole('button', { name: 'Continue to review & pay' });
  fireEvent.change(screen.getByLabelText('Customer name'), { target: { value: 'Wedding booking name' } });
  fireEvent.change(screen.getByLabelText('Email for booking updates (optional)'), { target: { value: 'booking@example.test' } });
  fireEvent.change(screen.getByLabelText('Special fitting instructions (optional)'), { target: { value: 'Please confirm the blouse adjustment.' } });
  first.unmount();
  render(<RentalBookingForm {...props} />);
  expect(screen.getByLabelText('Customer name')).toHaveValue('Wedding booking name');
  expect(screen.getByLabelText('Email for booking updates (optional)')).toHaveValue('booking@example.test');
  expect(screen.getByLabelText('Special fitting instructions (optional)')).toHaveValue('Please confirm the blouse adjustment.');
  expect(screen.queryByRole('button', { name: 'Reserve rental' })).not.toBeInTheDocument();
  expect(screen.queryByLabelText(/I accept these rental terms/)).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Check dates & review price' }));
  fireEvent.click(await screen.findByRole('button', { name: 'Continue to review & pay' }));
  expect(screen.getByRole('button', { name: 'Reserve rental' })).toBeDisabled();
  expect(api.post).toHaveBeenCalledTimes(2);
});
test('account changes do not expose or overwrite the previous account contact draft', () => {
  const firstUser = { _id: 'one', isPhoneVerified: true, name: 'First', phone: '9876543210' };
  const props = { listings: [listing], configuration, storeSlug: 'bridal' };
  const view = render(<RentalBookingForm {...props} user={firstUser} />);
  fireEvent.change(screen.getByLabelText('Customer name'), { target: { value: 'First private booking name' } });
  view.rerender(<RentalBookingForm {...props} user={{ ...firstUser, _id: 'two', name: 'Second' }} />);
  expect(screen.getByLabelText('Customer name')).toHaveValue('Second');
  const draft = JSON.parse(sessionStorage.getItem('rental-contact:bridal:one'));
  expect(draft.customer.name).toBe('First private booking name');
  expect(JSON.parse(sessionStorage.getItem('rental-contact:bridal:two')).customer.name).toBe('Second');
  view.rerender(<RentalBookingForm {...props} user={null} />);
  expect(screen.queryByLabelText('Customer name')).not.toBeInTheDocument();
});
